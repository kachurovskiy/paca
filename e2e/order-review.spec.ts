test('full holding closes require review, DAY for fractions, and renewed review for changed inventory', async ({ page }) => {
  const broker = new BrokerFixture();
  broker.positions = [{ symbol: 'QQQ', qty: '1.234567891', avg_entry_price: '100', side: 'long' }];
  await broker.install(page); await broker.connected(page);
  const ticket = page.locator('.order-ticket');
  await page.getByRole('button', { name: 'Close holding', exact: true }).click();
  await expect(ticket.getByRole('heading')).toHaveText('Trade QQQ'); expect(broker.writes).toHaveLength(0);
  await expect(ticket.locator('dl > div').filter({ hasText: 'Position after fill' })).toContainText('1.234567891 → 0 shares');
  await ticket.getByRole('group', { name: 'Duration', exact: true }).getByRole('button', { name: 'GTC', exact: true }).click();
  await expect(ticket.getByRole('alert')).toContainText('Choose Day'); await expect(ticket.locator('.submit-order')).toBeDisabled();
  await ticket.getByRole('group', { name: 'Duration', exact: true }).getByRole('button', { name: 'Day', exact: true }).click();
  await ticket.getByRole('button', { name: 'Sell QQQ', exact: true }).click();
  const confirmation = ticket.getByRole('region', { name: 'Confirm order', exact: true });
  await expect(confirmation).toContainText('entire holding'); expect(broker.writes).toHaveLength(0);
  await confirmation.getByRole('button', { name: 'Edit order' }).click();
  await expect(confirmation).toHaveCount(0); expect(broker.writes).toHaveLength(0);
  await ticket.getByRole('button', { name: 'Sell QQQ', exact: true }).click();
  broker.positions[0].qty = '2.5';
  await confirmation.getByRole('button', { name: 'Confirm sell QQQ', exact: true }).click();
  await expect(ticket.getByRole('status')).toContainText('whole shares');
  expect(broker.writes).toHaveLength(0);
  await ticket.getByLabel('Quantity', { exact: true }).fill('2.5');
  await page.getByRole('button', { name: 'Reconcile account', exact: true }).click();
  await ticket.getByRole('button', { name: 'Sell QQQ', exact: true }).click();
  await expect(confirmation).toContainText('Sell 2.5 QQQ'); expect(broker.writes).toHaveLength(0);
  await confirmation.getByRole('button', { name: 'Confirm sell QQQ', exact: true }).click();
  await expect(ticket.getByRole('status')).toContainText('Order acknowledged');
  expect(broker.writes).toHaveLength(1);
  expect(broker.writes[0].body).toMatchObject({ symbol: 'QQQ', qty: '2.5', side: 'sell', time_in_force: 'day', extended_hours: false });
  expect(broker.errors).toEqual([]);
});

test('large live orders require confirmation while small live orders submit directly', async ({ page }) => {
  const broker = new BrokerFixture(); await broker.install(page); await broker.connect(page, 'live');
  const ticket = page.locator('.order-ticket');
  await ticket.getByLabel('Arm live manual trading for this session').check();
  await ticket.getByLabel('Quantity', { exact: true }).fill('100');
  await ticket.getByRole('button', { name: 'Buy SPY', exact: true }).click();
  const confirmation = ticket.getByRole('region', { name: 'Confirm order', exact: true });
  await expect(confirmation).toContainText('$10,000 or more'); expect(broker.writes).toHaveLength(0);
  await confirmation.getByRole('button', { name: 'Edit order' }).click();
  await ticket.getByLabel('Quantity', { exact: true }).fill('1');
  await ticket.getByRole('button', { name: 'Buy SPY', exact: true }).click();
  await expect(ticket.getByRole('status')).toContainText('Order acknowledged');
  await expect(confirmation).toHaveCount(0); expect(broker.writes).toHaveLength(1);
  await ticket.getByRole('button', { name: 'New order', exact: true }).click();
  await page.getByLabel('Chart ticker').fill('QQQ'); await page.getByRole('button', { name: 'Go to ticker' }).click();
  await ticket.getByLabel('Quantity', { exact: true }).fill('100');
  await ticket.getByRole('button', { name: 'Buy QQQ', exact: true }).click();
  await confirmation.getByRole('button', { name: 'Confirm buy QQQ', exact: true }).click();
  await expect(ticket.getByRole('status')).toContainText('Order acknowledged');
  expect(broker.writes).toHaveLength(2);
  expect(await stored(page, 'manualCommands')).toHaveLength(2);
  expect(broker.errors).toEqual([]);
});

test('quote age advances without fresh quotes and stale limit orders are blocked', async ({ page }) => {
  const broker = new BrokerFixture(true); await broker.install(page); await broker.connected(page);
  const ticket = page.locator('.order-ticket');
  await ticket.getByRole('button', { name: 'Limit', exact: true }).click();
  await ticket.getByLabel('Limit price', { exact: true }).fill('100');
  broker.quoteTimestamp = new Date(broker.now).toISOString();
  await broker.advance(page, 31_000);
  await expect(ticket.locator('.ticket-quote-line')).toContainText('31s · stale');
  await expect(ticket.locator('.submit-order')).toBeDisabled();
  await expect(ticket.getByRole('alert')).toContainText('fresh');
  expect(broker.writes).toHaveLength(0); expect(broker.errors).toEqual([]);
});
