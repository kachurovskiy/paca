import { test, expect } from '@playwright/test';
import { BrokerFixture, stored } from './support/broker';

for (const standalone of [false, true]) {
  test(`${standalone ? 'standalone' : 'development'} summary matches explicit execution rules and validates price ticks`, async ({ page }) => {
    const broker = new BrokerFixture(); await broker.install(page, standalone); await broker.connected(page);
    const ticket = page.locator('.order-ticket'), summary = ticket.getByRole('region', { name: 'Order summary', exact: true });
    const row = (label: string) => summary.locator('dl > div').filter({ has: page.locator('dt', { hasText: new RegExp(`^${label}$`) }) });
    await expect(ticket.locator('.ticket-environment')).toHaveText('Paper');
    await expect(summary.locator('.ticket-order-line')).toHaveText('Buy 1 SPY · Market');
    await expect(summary.locator('.ticket-total')).toContainText('$101.20');
    await expect(summary.locator('.ticket-quote-line')).toHaveText('Spread $0.02 · Quote 0s');
    await expect(row('Available capital')).toContainText('$100,000.00');
    await expect(row('Position after fill')).toContainText('0 → 1 share');
    await expect(ticket.locator('select')).toHaveCount(0);
    const duration = ticket.getByRole('group', { name: 'Duration', exact: true });
    const sessions = ticket.getByRole('group', { name: 'Trading sessions', exact: true });
    await expect(duration.getByRole('button', { name: 'Day', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await expect(sessions.getByRole('button', { name: 'Regular', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await expect(sessions.getByRole('button', { name: '+ Extended', exact: true })).toBeDisabled();
    await expect(row('Paca reservations')).not.toBeVisible();
    await summary.locator('summary').click();
    await expect(row('Paca reservations')).toBeVisible();
    await summary.locator('summary').click();
    await ticket.getByRole('button', { name: 'Limit', exact: true }).click();
    await expect(ticket.getByLabel('Limit price', { exact: true })).toHaveValue('101.21');
    await ticket.getByLabel('Limit price', { exact: true }).fill('1.001');
    await expect(ticket.getByRole('alert')).toContainText('$0.01 increments');
    await expect(ticket.locator('.submit-order')).toBeDisabled();
    await ticket.locator('form').evaluate((form: HTMLFormElement) => form.requestSubmit());
    expect(broker.writes).toHaveLength(0);
    await ticket.getByLabel('Limit price', { exact: true }).fill('0.12345');
    await expect(ticket.getByRole('alert')).toContainText('$0.0001 increments');
    await ticket.getByLabel('Limit price', { exact: true }).fill('0.1234');
    await expect(summary.locator('.ticket-order-line')).toContainText('Limit $0.1234');
    await sessions.getByRole('button', { name: '+ Extended', exact: true }).click();
    await duration.getByRole('button', { name: 'GTC', exact: true }).click();
    await expect(summary.locator('.ticket-execution-line')).toHaveText('GTC · Regular + extended hours');
    await ticket.getByRole('button', { name: 'Market', exact: true }).click();
    await expect(sessions.getByRole('button', { name: 'Regular', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await ticket.getByRole('button', { name: 'Limit', exact: true }).click();
    await expect(sessions.getByRole('button', { name: 'Regular', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await sessions.getByRole('button', { name: '+ Extended', exact: true }).click();
    await ticket.getByRole('button', { name: 'Buy SPY', exact: true }).click();
    await expect(ticket.getByRole('status')).toContainText('Order acknowledged');
    expect(broker.writes[0].body).toMatchObject({ symbol: 'SPY', qty: '1', side: 'buy', limit_price: '0.1234', time_in_force: 'gtc', extended_hours: true });
    await expect(summary.locator('.ticket-execution-line')).toHaveText('GTC · Regular + extended hours');
    await expect(duration.getByRole('button', { name: 'GTC', exact: true })).toBeDisabled();
    expect(broker.errors).toEqual([]);
  });
}

test('limit defaults use the executable quote and preserve explicit edits and clearing', async ({ page }) => {
  const broker = new BrokerFixture(true); await broker.install(page); await broker.connected(page);
  const ticket = page.locator('.order-ticket');
  await ticket.getByRole('button', { name: 'Limit', exact: true }).click();
  const limit = ticket.getByLabel('Limit price', { exact: true });
  await expect(limit).toHaveValue('101.21');
  await limit.fill('99.25');
  await broker.advance(page, 5000);
  await expect(limit).toHaveValue('99.25');
  await limit.fill('');
  await broker.advance(page, 5000);
  await expect(limit).toHaveValue('');
  await ticket.getByRole('button', { name: 'Sell holdings', exact: true }).click();
  await expect(limit).toHaveValue('101.19');
  await limit.fill('102');
  await page.getByLabel('Chart ticker').fill('QQQ'); await page.getByRole('button', { name: 'Go to ticker' }).click();
  await expect(limit).toHaveValue('101.19');
  expect(broker.writes).toHaveLength(0); expect(broker.errors).toEqual([]);
});

